#!/usr/bin/env python3
"""Generate the app screen texts for both platforms from tools/ui_texts.json.

    python3 tools/build_ui_texts.py            # ios/App/UiTexts.swift
    python3 tools/build_ui_texts.py --android  # android-app/.../UiTexts.kt as well
    python3 tools/build_ui_texts.py --check    # gates only, writes nothing

One source, so a sentence fixed once is fixed on both platforms (before this
the same texts were typed twice, in Ui.kt and Ui.swift, and drifted).
Serbian Cyrillic (`sr-Cyrl`) is transliterated from Serbian Latin (`sr`):
the two alphabets map one to one; product names and tokens stay as they are.
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "ui_texts.json"
IOS = ROOT / "ios" / "App" / "UiTexts.swift"
ANDROID = ROOT / "android-app/app/src/interslove/kotlin/com/radoslove/interslavic/UiTexts.kt"

# `č š ž ě` in a sentence ABOUT the Interslavic letters stays Latin.
KEEP = re.compile(r"č š ž ě|Interslove|QWERTZ|QWERTY|JSON|ABC|MB|ID|iOS|Android|Gmail|Shift|\{n\}|[\w.+-]+@[\w.-]+|https?://\S+")
SR_PAIRS = [("dž", "џ"), ("Dž", "Џ"), ("DŽ", "Џ"), ("lj", "љ"), ("Lj", "Љ"), ("LJ", "Љ"),
            ("nj", "њ"), ("Nj", "Њ"), ("NJ", "Њ")]
SR_ONE = dict(zip("abvgdđežzijklmnoprstćufhcčš", "абвгдђежзијклмнопрстћуфхцчш"))
SR_ONE.update({k.upper(): v.upper() for k, v in list(SR_ONE.items())})


def sr_cyrl(text: str) -> str:
    out, last = [], 0
    for m in KEEP.finditer(text):
        out.append(_tr(text[last:m.start()])); out.append(m.group(0)); last = m.end()
    out.append(_tr(text[last:]))
    return "".join(out)


def _tr(s: str) -> str:
    for a, b in SR_PAIRS:
        s = s.replace(a, b)
    return "".join(SR_ONE.get(c, c) for c in s)


def load():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    langs, texts = data["languages"], data["texts"]
    for row in texts.values():
        if "sr" in row:
            row["sr-Cyrl"] = sr_cyrl(row["sr"])
    return langs + ["sr-Cyrl"], texts


def check(langs, texts):
    errors = []
    for k, row in texts.items():
        if "en" not in row:
            errors.append(f"{k}: no en")
        for l in langs:
            v = row.get(l)
            if v is None:
                continue
            for tok in ("{n}", "🌐", "⚙", "＋", "Interslove"):
                if tok in row["en"] and tok not in v and l != "isv":
                    errors.append(f"{k}/{l}: lost {tok!r}")
            if l == "sr-Cyrl" and re.search(r"[a-zčćđšž]", KEEP.sub("", v)):
                errors.append(f"{k}/sr-Cyrl: Latin left")
    missing = {l: sum(1 for r in texts.values() if l not in r) for l in langs}
    return errors, missing


def swift(langs, texts):
    def lit(s):
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'
    rows = []
    for k in sorted(texts):
        row = texts[k]
        if "ios" not in row["platforms"]:
            continue
        cells = ", ".join(f"{lit(l)}: {lit(row[l])}" for l in langs if l in row)
        rows.append(f"        {lit(k)}: [{cells}],")
    return ("// GENERATED by tools/build_ui_texts.py from tools/ui_texts.json - do not edit.\n\n"
            "extension Ui {\n    static let table: [String: [String: String]] = [\n"
            + "\n".join(rows) + "\n    ]\n\n    static let languages: [String] = ["
            + ", ".join(lit(l) for l in langs) + "]\n}\n")


def kotlin(langs, texts):
    def lit(s):
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("\n", "\\n") + '"'
    rows = []
    for k in sorted(texts):
        row = texts[k]
        if "android" not in row["platforms"]:
            continue
        cells = ", ".join(f"{lit('ms' if l == 'isv' else l)} to {lit(row[l])}" for l in langs if l in row)
        rows.append(f"        {lit(k)} to mapOf({cells}),")
    return ("// GENERATED by tools/build_ui_texts.py from tools/ui_texts.json - do not edit.\n"
            "package com.radoslove.interslavic\n\nobject UiTexts {\n"
            "    val TEXT: Map<String, Map<String, String>> = mapOf(\n" + "\n".join(rows) + "\n    )\n"
            "    val LANGUAGES = listOf(" + ", ".join(lit('ms' if l == 'isv' else l) for l in langs) + ")\n}\n")


def main():
    langs, texts = load()
    errors, missing = check(langs, texts)
    print(f"{len(texts)} keys; missing per language: " + ", ".join(f"{l} {n}" for l, n in missing.items() if n))
    if errors:
        print("\n".join(errors)); sys.exit(1)
    if "--check" in sys.argv:
        return
    IOS.write_text(swift(langs, texts), encoding="utf-8")
    print(f"wrote {IOS.relative_to(ROOT)}")
    if "--android" in sys.argv:
        ANDROID.write_text(kotlin(langs, texts), encoding="utf-8")
        print(f"wrote {ANDROID.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
